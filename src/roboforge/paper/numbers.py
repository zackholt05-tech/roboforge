    for pkg in ("robosuite", "robomimic"):
        v, commit = src.lock_version(pkg).split("@")
        n.set(f"ver.{pkg}", v)
        n.set(f"ver.{pkg}.commit", commit[:7])
    plat = src.yaml("platform_config")
    n.set("ver.python", plat["python"])
    n.set("plat.image", plat["image_id"].split(":")[1][:12])

    man = src.json("data_manifest")
