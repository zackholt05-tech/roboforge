"""Write ``docs/VISUAL_PROVENANCE.md`` from the committed Observatory export (MASTER_SPEC §8.5).

The ledger lists every visual output of the site with its source run, checkpoint, seed, start,
simulator build and the transformations applied. It is generated, never edited by hand:

    make visual-provenance      # host: reads reports/session<N>/observatory/ and, for the
                                # v1.1 extension clips (D-134), reports/session18/observatory/;
                                # the Session 20 re-verification (D-136) is its own section
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path
from typing import Any

from roboforge.paths import REPO_ROOT, repo_relative
from roboforge.provenance import sha256_file

TRANSFORMS = {
    "clip": "body and geom world poses recomputed with mj_kinematics from the recorded states "
            "(never stepped), compared with the recorded poses; rounded to 6 decimals",
    "media": "MuJoCo frontview render of the recorded states, 256², 20 fps (D-074 path)",
    "reference_frames": "MuJoCo frontview and agentview at 480²: RGB, and a class mask from "
                        "segmentation with sites hidden (D-091)",
    "denoise": "the frozen checkpoint's sampler re-run on the recorded validation episode, "
               "checked bitwise against the recorded actions; candidate paths by clone "
               "simulation (replay to the decision, then the candidate chunk); 16 extra seeds",
    "clouds": "the policy's 512-point input cloud recomputed from the recorded state at each "
              "decision frame by the frozen D-083 path",
    "policy_views": "the RGB policy's two 84² camera inputs rendered from the recorded state "
                    "at each decision frame",
}


def _clip(out: Path, cid: str) -> dict[str, Any]:
    with gzip.open(out / "clips" / f"{cid}.json.gz") as fh:
        return json.load(fh)


def build(out: Path, ext: Path | None = None, reverify: Path | None = None) -> str:
    """The ledger's Markdown text; ``ext`` adds the v1.1 extension export (D-134)."""
    index = json.loads((out / "index.json").read_text())
    lines = [
        "# Visual provenance ledger",
        "",
        "Generated by `make visual-provenance` from the committed Observatory export; do not "
        "edit by hand (MASTER_SPEC §8.5, DECISIONS D-089).",
        "",
        f"- Export: `{repo_relative(out)}/index.json` (SHA-256 "
        f"`{sha256_file(out / 'index.json')}`), {len(index['clips'])} clips, "
        f"{len(index['files'])} files.",
        f"- Exported on `{index['platform']['platform_id']}` from commit "
        f"`{index['git']['sha'][:10]}` (clean: {not index['git']['dirty']}), "
        f"{index['wall_s'] / 3600:.2f} h.",
        "- Every rollout is a recorded evaluation episode. Held-out and robustness records are "
        "re-rendered from their states and never re-run; only validation records are replayed "
        "(Inside the policy).",
        "",
        "## Transformations",
        "",
        *[f"- **{k}**: {v}." for k, v in TRANSFORMS.items()],
        "- **website**: the browser draws a restyled 3D reconstruction of the same poses; its "
        "approximations are listed on the site (Methods) and in "
        "`website/src/sections/Methods.tsx`. Robot meshes are extracted from the installed "
        "robosuite at build time (D-090), never committed.",
        "- **overlays**: `reports/session9/pc_feasibility/.../lift_overlay_*.png`, Session 9 "
        "calibration renders, copied unmodified.",
        "",
        "## Outputs",
        "",
        "| Clip | Roles | Policy, seed | Checkpoint (step, SHA-256) | Start | Evaluation run | "
        "Simulator | Outputs |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for e in index["clips"]:
        c = _clip(out, e["id"])
        pk = c["provenance"]["simulator"]["packages"]
        ck = e["checkpoint"]
        cks = f"{ck['step']}, `{ck['sha256'][:12]}`" if ck.get("sha256") else "none (non-learned)"
        outs = ["clip", "media", *e["has"]]
        lines.append(
            f"| `{e['id']}` | {', '.join(e['roles'])} | {c['policy']['name']}, {e['seed']} | "
            f"{cks} | `{e['state_id']}` ({e['partition']}) | `{e['eval_run_id']}` | "
            f"MuJoCo {pk.get('mujoco')}, robosuite {pk.get('robosuite')} | {', '.join(outs)} |")
    lines += ["", "## Viewer verification", "", *_verification(out, "make web-verify")]
    if ext is not None:
        lines += _extension(ext)
    if reverify is not None:
        lines += _reverification(reverify)
    return "\n".join(lines) + "\n"


def _verification(out: Path, target: str) -> list[str]:
    ver_p = out / "viewer_verification.json"
    if not ver_p.exists():
        return [f"Not run yet (`{target}`)."]
    ver = json.loads(ver_p.read_text())
    fr = ver["frames"]
    return [
        f"`{repo_relative(ver_p)}`: {len(fr)} reference frames, overall "
        f"**{'pass' if ver['pass'] else 'FAIL'}** (thresholds {ver['threshold']}).",
        f"Robot IoU {min(f['robot_iou'] for f in fr):.4f}–"
        f"{max(f['robot_iou'] for f in fr):.4f}; object IoU "
        f"{min(f['object_iou'] for f in fr if f['object_iou'] is not None):.4f}–"
        f"{max(f['object_iou'] for f in fr if f['object_iou'] is not None):.4f}; "
        f"robot centroid offset at most {max(f['robot_centroid_px'] for f in fr):.2f} px.",
        f"Method: {ver['method']}.",
    ]


def _extension(ext: Path) -> list[str]:
    """The v1.1 extension clips (D-134): their own export, rows and viewer verification."""
    index = json.loads((ext / "index.json").read_text())
    lines = [
        "", "## v1.1 extension clips (D-134)", "",
        f"- Export: `{repo_relative(ext)}/index.json` "
        f"(SHA-256 `{sha256_file(ext / 'index.json')}`), {len(index['clips'])} clips, "
        f"{len(index['files'])} files; selection by the D-134 rules "
        f"(`{repo_relative(ext)}/selection.json`, SHA-256 `{index['selection_sha256']}`).",
        f"- Exported on `{index['platform']['platform_id']}` from commit "
        f"`{index['git']['sha'][:10]}` (clean: {not index['git']['dirty']}), "
        f"{index['wall_s'] / 3600:.2f} h.",
        "- X1 and X2 records re-rendered from their recorded states with the **clip**, **media** "
        "and **reference_frames** transformations above; nothing was run again. X2 clips carry "
        "the display label \"X2 (Can MH): trained on the robomimic Can MH demonstrations\"; the "
        "evaluator's recorded label is kept as `provenance.recorded_policy_label` (KI-065).",
        "",
        "| Clip | Study, arm | Roles | Policy, seed | Checkpoint (step, SHA-256) | Start | "
        "Evaluation run | Simulator | Outputs |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for e in index["clips"]:
        c = _clip(ext, e["id"])
        pk = c["provenance"]["simulator"]["packages"]
        ck = e["checkpoint"]
        lines.append(
            f"| `{e['id']}` | {e['study'].upper()}, {e['arm']} | {', '.join(e['roles'])} | "
            f"{c['policy']['name']}, {e['seed']} | {ck['step']}, `{ck['sha256'][:12]}` | "
            f"`{e['state_id']}` ({e['partition']}) | `{e['eval_run_id']}` | "
            f"MuJoCo {pk.get('mujoco')}, robosuite {pk.get('robosuite')} | "
            f"{', '.join(['clip', 'media', *e['has']])} |")
    return [*lines, "", "### Viewer verification (extension clips)", "",
            *_verification(ext, "make web-verify-ext")]


def _reverification(rev: Path) -> list[str]:
    """Session 20 (D-136): both verifications run again after the visual pass, in their own tree."""
    return [
        "", "## Viewer re-verification after the visual pass (Session 20, D-136)", "",
        "The visual quality pass changed styled materials, lights and viewer camera presets "
        "under `website/src/three/`. Both verifications above were run again with the same page, "
        "checks and thresholds, writing to a new tree; the results above were not rewritten.",
        "", "Release clips (`make web-verify-s20`):", "",
        *_verification(rev, "make web-verify-s20"),
        "", "Extension clips (`make web-verify-ext-s20`):", "",
        *_verification(rev / "ext", "make web-verify-ext-s20"),
    ]


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint."""
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out-dir", type=Path, required=True)
    p.add_argument("--ext-dir", type=Path, default=None,
                   help="the v1.1 extension export (D-134), added as its own section")
    p.add_argument("--reverify-dir", type=Path, default=None,
                   help="the Session 20 re-verification tree (D-136), added as its own section")
    p.add_argument("--doc", type=Path, default=REPO_ROOT / "docs" / "VISUAL_PROVENANCE.md")
    a = p.parse_args(argv)
    out = a.out_dir if a.out_dir.is_absolute() else REPO_ROOT / a.out_dir
    ext = None if a.ext_dir is None else (a.ext_dir if a.ext_dir.is_absolute()
                                          else REPO_ROOT / a.ext_dir)
    rev = None if a.reverify_dir is None else (
        a.reverify_dir if a.reverify_dir.is_absolute() else REPO_ROOT / a.reverify_dir)
    a.doc.write_text(build(out, ext, rev))
    print(f"wrote {repo_relative(a.doc)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
