"""Every number the paper's prose uses, as ``\\rf{key}`` macros (DECISIONS D-094).

Values are copied from the frozen sources and formatted at the frozen tables' rounding; the
few derived values are plain arithmetic (sums of counts, counts of selections, unit
conversions, the KI-049 correction) and are listed in ``DERIVED`` with their formula. The only
new statistics are the labelled, not preregistered ones of ``sensitivity`` (D-095) and the
plain means of ``secondary`` (D-096).
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from typing import Any

from roboforge.paper import fmt, secondary, sensitivity
from roboforge.paper.sources import Sources

L1_FAMILIES = ["bc_mlp", "bc_rnn", "bc_mlp_chunk", "diffusion_unet", "random_uniform"]
LEARNED = ["bc_mlp", "bc_rnn", "bc_mlp_chunk", "diffusion_unet"]
TASKS = ["lift", "can"]

DERIVED = {
    "*.k / *.n": "sum of successes / episodes over the 3 per-checkpoint entries (results.json)",
    "l1.bc.first-ckpt": "count of BC-family selections at the first checkpoint step",
    "*.contrasts": "count of reported differences and contrasts in one analysis block",
    "l2.train.s0.msstep.fixed": "train_wall_s / (end_step - resumed_from_step) of the seed-0 "
                                "launch record",
    "*.cpuh.*, *.wallh.*": "seconds / 3600 or min/max over runs, copied hours",
    "spend.*": "sum of billed_usd of the cost ledger's billing events, by approval",
    "sel.*": "mean of the selected checkpoints' validation successes / 50 (suite summaries)",
    "*.succpart, *.speedpart": "D-095 split of a censored-length difference: "
                               "-(p_a - p_b)(H - T_b) and p_a (T_a - T_b)",
    "sens.*": "D-095 seed-level t intervals on the frozen per-seed rates (sensitivity.py)",
    "sec.*": "D-096 means of per-episode declared secondary metrics of the hash-chained "
             "held-out summaries (secondary.py)",
}


class Numbers:
    """An ordered key -> LaTeX value store; keys use letters, digits, '.' and '-'."""

    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def set(self, key: str, value: str | int) -> None:
        """Define one key; a key may be defined once."""
        if key in self.values:
            raise KeyError(f"number {key} defined twice")
        if not all(c.isalnum() or c in ".-" for c in key):
            raise ValueError(f"bad number key {key!r}")
        self.values[key] = str(value)

    def tex(self) -> str:
        """The ``numbers.tex`` body: one ``\\csname`` definition per key."""
        lines = [
            "% Generated by scripts/paper_assets.py from frozen sources (DECISIONS D-094).",
            "% Do not edit. Provenance: paper/generated/index.json.",
        ]
        for k, v in self.values.items():
            lines.append(f"\\expandafter\\def\\csname rf@{k}\\endcsname{{{v}}}")
        return "\n".join(lines) + "\n"


def _fam_seed(d: dict[str, Any], key: str, n: Numbers, per_seed_whole: bool = True) -> None:
    n.set(key + ".succ", fmt.pct(d["estimate"]))
    n.set(key + ".lo", fmt.pct(d["ci95"][0]))
    n.set(key + ".hi", fmt.pct(d["ci95"][1]))
    for i, x in enumerate(d["per_seed"]):
        n.set(f"{key}.s{i}", fmt.pct0(x) if per_seed_whole else fmt.pct(x))


def _diff(d: dict[str, Any], key: str, n: Numbers, pct: bool = True,
          value_key: str = "difference") -> None:
    v = d[value_key]
    if pct:
        n.set(key + ".d", fmt.spct(v))
        n.set(key + ".lo", fmt.spct(d["ci95"][0]))
        n.set(key + ".hi", fmt.spct(d["ci95"][1]))
    else:
        n.set(key + ".d", fmt.snum1(v))
        n.set(key + ".lo", fmt.snum1(d["ci95"][0]))
        n.set(key + ".hi", fmt.snum1(d["ci95"][1]))
    n.set(key + ".sep", fmt.sep(d["separation"]))


def _fk(f: str) -> str:
    return fmt.FAMILY_KEY[f]


def _sum_k(entries: Iterable[dict[str, Any]], k: str = "successes", nn: str = "n_episodes"
           ) -> tuple[int, int]:
    es = list(entries)
    return sum(e[k] for e in es), sum(e[nn] for e in es)


