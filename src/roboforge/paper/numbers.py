    for t in TASKS:
        files = {f["hdf5_type"]: f for f in man["files"] if f["task"] == t}
        n.set(f"data.{t}.lowdim.sha", files["low_dim"]["sha256"][:8])
        sp = src.json(f"split_{t}")
        n.set(f"data.{t}.demos", sp["counts"]["total"])
        n.set(f"data.{t}.train", sp["counts"]["train"])
        n.set(f"data.{t}.valid", sp["counts"]["valid"])
        n.set(f"data.{t}.samples", fmt.thousands(sp["samples"]["train"] + sp["samples"]["valid"]))

    audit = src.json("data_audit")
