"""Build or check ``paper/generated/`` from the frozen sources (DECISIONS D-094).

``build_all`` computes every output in memory: tables, figures with their data sidecars,
copied renders, ``numbers.tex`` and ``index.json`` (each output's SHA-256 and the path and
SHA-256 of every source it read). ``write`` puts them on disk; ``check`` compares them with the
committed files byte for byte, except ``index.json``'s generating git SHA.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from roboforge.paper import figures, tables
from roboforge.paper.numbers import DERIVED, build_numbers
from roboforge.paper.sources import SOURCES, Sources
from roboforge.paths import REPO_ROOT
from roboforge.provenance import git_revision

OUT = "paper/generated"
INDEX_SCHEMA = "roboforge.paper_assets/1"


def _header(src: Sources, out: str) -> str:
    lines = ["% Generated by scripts/paper_assets.py (DECISIONS D-094). Do not edit.",
             "% Sources (path sha256):"]
    for key in sorted(src.used[out]):
        s = SOURCES[key]
        lines.append(f"%   {s.path} {s.sha256}")
    chained = src.chained.get(out, {})
    if chained:
        lines.append(f"% Plus {len(chained)} files hash-chained from the sources above, listed in "
                     "index.json.")
    return "\n".join(lines) + "\n"


def build_all(root: Path = REPO_ROOT) -> dict[str, bytes]:
    """Every output of ``paper/generated/`` as ``{relative path: bytes}``."""
    src = Sources(root=root)
    problems = src.verify_all()
    if problems:
        raise RuntimeError("frozen sources differ from their pins:\n" + "\n".join(problems))
    files: dict[str, bytes] = {}
    entries: list[dict[str, Any]] = []

    def add(rel: str, data: bytes, kind: str, used: set[str], extra: dict[str, Any] | None = None
            ) -> None:
        files[rel] = data
        e = {"path": rel, "kind": kind, "sha256": hashlib.sha256(data).hexdigest(),
             "sources": [{"path": SOURCES[k].path, "sha256": SOURCES[k].sha256}
                         for k in sorted(used)]}
        chained = src.chained.get(rel.replace(".json", ".pdf"), {}) if kind == "figure-data" \
            else src.chained.get(rel, {})
        if chained:
            e["chained_sources"] = [{"path": p, "sha256": h} for p, h in sorted(chained.items())]
        if extra:
            e.update(extra)
        entries.append(e)

    for name, fn in tables.TABLES.items():
        rel = f"{OUT}/tables/{name}.tex"
        src.begin(rel)
        body = fn(src)
        add(rel, (_header(src, rel) + body).encode(), "table", src.used[rel])

    for name, fn in figures.FIGURES.items():
        rel = f"{OUT}/figures/{name}.pdf"
        src.begin(rel)
        fig, data = fn(src)
        pdf = figures.pdf_bytes(fig)
        side = json.dumps({"figure": rel, "plotted_values": data}, indent=1,
                          sort_keys=True).encode() + b"\n"
        add(rel, pdf, "figure", src.used[rel])
        add(rel.replace(".pdf", ".json"), side, "figure-data", src.used[rel])

    for name, (directory, sha, what) in figures.RENDERS.items():
        path = figures.find_render(root, directory, sha)
        data = (root / path).read_bytes()
        rel = f"{OUT}/figures/{name}.png"
        files[rel] = data
        entries.append({"path": rel, "kind": "render", "sha256": hashlib.sha256(data).hexdigest(),
                        "what": what, "sources": [{"path": path, "sha256": sha}]})

    rel = f"{OUT}/numbers.tex"
    src.begin(rel)
    nums = build_numbers(src)
    add(rel, (_header(src, rel) + nums.tex()).encode(), "numbers", src.used[rel],
        {"n_keys": len(nums.values), "derived": DERIVED})

    index = {
        "schema": INDEX_SCHEMA,
        "decision": "D-094",
        "generator": "scripts/paper_assets.py (roboforge.paper)",
        "note": "Values copied from the frozen sources at their tables' rounding; derived values "
                "are plain arithmetic, listed under numbers.tex 'derived'. findings.json and "
                "runs/ are never read.",
        "git": git_revision(root),
        "outputs": sorted(entries, key=lambda e: e["path"]),
    }
    files[f"{OUT}/index.json"] = (json.dumps(index, indent=1, sort_keys=True) + "\n").encode()
    return files


def write(files: dict[str, bytes], root: Path = REPO_ROOT) -> list[str]:
    """Write every output and remove stale files under paper/generated; return written paths."""
    out_dir = root / OUT
    keep = set(files)
    for p in sorted(out_dir.rglob("*")) if out_dir.exists() else []:
        if p.is_file() and p.relative_to(root).as_posix() not in keep:
            p.unlink()
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return sorted(files)


def _index_without_git(data: bytes) -> Any:
    d = json.loads(data)
    d.pop("git", None)
    return d


def check(files: dict[str, bytes], root: Path = REPO_ROOT) -> list[str]:
    """Differences between the in-memory build and the committed ``paper/generated``."""
    problems = []
    out_dir = root / OUT
    on_disk = {p.relative_to(root).as_posix() for p in out_dir.rglob("*") if p.is_file()} \
        if out_dir.exists() else set()
    for rel in sorted(set(files) | on_disk):
        if rel not in files:
            problems.append(f"{rel}: on disk but not generated")
        elif rel not in on_disk:
            problems.append(f"{rel}: generated but missing on disk")
        elif rel.endswith("index.json"):
            if _index_without_git(files[rel]) != _index_without_git((root / rel).read_bytes()):
                problems.append(f"{rel}: differs (ignoring its git field)")
        elif (root / rel).read_bytes() != files[rel]:
            problems.append(f"{rel}: differs")
    return problems
